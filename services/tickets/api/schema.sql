-- Mobile / POS booking tables (live alongside legacy ticket tables).
-- Safe to re-run.

CREATE TABLE IF NOT EXISTS mobile_trips (
    id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    tenant_id      INT UNSIGNED  NOT NULL DEFAULT 1,
    bus_name       VARCHAR(100)  NOT NULL,
    route          VARCHAR(200)  NOT NULL,
    from_city      VARCHAR(100)  NOT NULL,
    to_city        VARCHAR(100)  NOT NULL,
    via_city       VARCHAR(100)  DEFAULT '',
    from_terminal  VARCHAR(200)  DEFAULT '',
    to_terminal    VARCHAR(200)  DEFAULT '',
    departure_time TIME          NOT NULL,
    arrival_time   TIME          NOT NULL,
    arr_next_day   TINYINT(1)    NOT NULL DEFAULT 0,
    duration       VARCHAR(50)   DEFAULT '',
    fare           DECIMAL(10,2) NOT NULL DEFAULT 0,
    seat_class     VARCHAR(50)   NOT NULL DEFAULT 'VIP',
    total_seats    INT           NOT NULL DEFAULT 49,
    driver         VARCHAR(100)  DEFAULT '',
    conductor      VARCHAR(100)  DEFAULT '',
    trip_date      DATE          NOT NULL,
    amenities      JSON,
    boarding_stops JSON,
    dropping_stops JSON,
    legacy_route_id INT DEFAULT NULL,
    created_at     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_route_date (from_city, to_city, trip_date),
    INDEX idx_mobile_trips_tenant (tenant_id),
    INDEX idx_mobile_trips_tenant_route (tenant_id, from_city, to_city, trip_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mobile_bookings (
    id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    tenant_id       INT UNSIGNED  NOT NULL DEFAULT 1,
    booking_ref     VARCHAR(30)   NOT NULL UNIQUE,
    trip_id         INT UNSIGNED  NOT NULL,
    seat_number     VARCHAR(10)   NOT NULL,
    first_name      VARCHAR(100)  NOT NULL,
    last_name       VARCHAR(100)  NOT NULL,
    phone           VARCHAR(25)   NOT NULL,
    email           VARCHAR(200)  DEFAULT '',
    gender          VARCHAR(10)   DEFAULT 'Male',
    passenger_type  VARCHAR(20)   DEFAULT 'Adult',
    boarding_stop   VARCHAR(100)  DEFAULT '',
    dropping_stop   VARCHAR(100)  DEFAULT '',
    payment_method  VARCHAR(50)   DEFAULT '',
    payment_phone   VARCHAR(25)   DEFAULT '',
    payment_status  VARCHAR(30)   NOT NULL DEFAULT 'pending',
    clickpesa_id    VARCHAR(100)  DEFAULT '',
    fare            DECIMAL(10,2) NOT NULL DEFAULT 0,
    levy            DECIMAL(10,2) NOT NULL DEFAULT 0,
    total           DECIMAL(10,2) NOT NULL DEFAULT 0,
    status          VARCHAR(20)   NOT NULL DEFAULT 'pending',
    channel         VARCHAR(30)   NOT NULL DEFAULT 'customer_app',
    agent_username  VARCHAR(80)   DEFAULT '',
    booked_at       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_booking_ref (booking_ref),
    INDEX idx_trip_seat   (trip_id, seat_number),
    INDEX idx_phone       (phone),
    INDEX idx_mobile_bookings_tenant (tenant_id),
    INDEX idx_mobile_bookings_tenant_ref (tenant_id, booking_ref),
    CONSTRAINT fk_mobile_bookings_trip
      FOREIGN KEY (trip_id) REFERENCES mobile_trips(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
